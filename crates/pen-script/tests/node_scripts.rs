//! `script` nodes end to end: header, QuickJS run, generated subtree in the scene,
//! layout, display list, caching, errors and a golden render.
//!
//! Script files are written under `target/node-scripts/` at test time. The legacy sample
//! scripts (`legacy/extracted/editor/goodies/scripts`, proprietary, never committed) are
//! copied there too when present and must all run.

use std::path::{Path, PathBuf};
use std::time::Instant;

use pen_doc::{DocOp, Kind, SceneDoc};
use pen_layout::{NoAssets, Pipeline, TextEngine};
use pen_render::{Color, DisplayItem, Rect};
use pen_script::ScriptNodeRunner;

fn workspace() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("workspace root")
        .to_path_buf()
}

/// Fresh directory `target/node-scripts/<name>`.
fn dir(name: &str) -> PathBuf {
    let d = workspace().join("target").join("node-scripts").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

struct H {
    scene: SceneDoc,
    pipe: Pipeline,
}

impl H {
    fn new(dir: &Path, json: &str) -> H {
        let (mut scene, _) =
            SceneDoc::load(json.as_bytes(), Some(dir), &pen_doc::NoLibraries).expect("load");
        let mut pipe = Pipeline::new(TextEngine::new(), Box::new(NoAssets));
        pipe.set_script_runner(Box::new(ScriptNodeRunner::new()));
        pipe.rebuild(&mut scene);
        H { scene, pipe }
    }

    fn key(&self, id: &str) -> pen_doc::NodeKey {
        self.scene
            .find(id)
            .unwrap_or_else(|| panic!("no node {id}"))
    }

    fn set(&mut self, id: &str, patch: serde_json::Value) {
        let k = self.key(id);
        let (node, _) = pen_schema::node_from_value(patch, "test");
        self.scene
            .apply(DocOp::set(self.scene.node_ref(k).unwrap(), node))
            .unwrap();
        self.pipe.update(&mut self.scene);
    }

    fn runs(&self) -> u64 {
        self.pipe.scripts.as_ref().unwrap().stats.runs
    }

    /// Items of the display list drawn for nodes generated by `script`.
    fn generated_items(&self, script: &str) -> usize {
        let s = self.key(script);
        self.pipe
            .list
            .chunks
            .iter()
            .flat_map(|c| &c.items)
            .filter(|it| match it {
                DisplayItem::Shape { node, .. } | DisplayItem::Text { node, .. } => {
                    self.scene.generated_owner(*node) == Some(s)
                }
                _ => false,
            })
            .count()
    }
}

fn doc(script_node: &str) -> String {
    format!(
        r##"{{ "version": "2.22", "children": [
  {{ "type": "frame", "id": "page", "x": 0, "y": 0, "width": 240, "height": 160, "fill": "#ffffff",
     "layout": "none", "children": [ {script_node} ] }}
] }}"##
    )
}

const BARS: &str = r##"/**
 * @schema 2.11
 * @input rows: number(min=1, max=20) = 3
 * @input color: color = #3B82F6
 * @input label: string = "Bar"
 */
const rows = Math.floor(pencil.input.rows);
const h = pencil.height / rows;
const out = [];
for (let i = 0; i < rows; i++) {
  out.push({
    type: "rectangle", name: pencil.input.label + " " + (i + 1), x: 0, y: i * h,
    width: pencil.width * (0.3 + 0.7 * Math.random()), height: h - 4,
    fill: pencil.input.color, cornerRadius: 4,
  });
}
out.push({ type: "text", x: 4, y: 2, content: "w=" + pencil.width, fontSize: 10, fill: "#000000" });
return out;
"##;

#[test]
fn script_generates_children_and_reruns_on_resize() {
    let d = dir("bars");
    std::fs::write(d.join("bars.js"), BARS).unwrap();
    let mut h = H::new(
        &d,
        &doc(
            r##"{ "type": "script", "id": "s", "x": 20, "y": 20, "width": 200, "height": 120,
              "clip": true, "scriptUri": "./bars.js", "inputs": { "rows": 4, "color": "#ff0000" } }"##,
        ),
    );
    let s = h.key("s");
    let gen_keys = h.scene.generated(s).to_vec();
    assert_eq!(gen_keys.len(), 5, "4 bars + label");
    assert_eq!(h.runs(), 1);
    assert!(h.scene.script_error(s).is_none());
    // Generated nodes are resolved, laid out and drawn, but not part of the document.
    let first = h.scene.get(gen_keys[0]).unwrap();
    assert_eq!(first.kind, Kind::Rectangle);
    assert_eq!(first.name.as_deref(), Some("Bar 1"));
    assert!(h.scene.id_path(gen_keys[0]).is_none());
    assert!(h.scene.node_ref(gen_keys[0]).is_none());
    assert!(h.scene.children(s).is_empty());
    let r = h.pipe.node_rect(&h.scene, gen_keys[1]).unwrap();
    assert!(
        (r.x - 20.0).abs() < 1e-3 && (r.y - 50.0).abs() < 1e-3,
        "{r:?}"
    );
    assert_eq!(h.generated_items("s"), 5);
    assert!(!h.scene.save().contains("Bar 1"));

    // Deterministic Math.random: a second scene gives identical widths.
    let mut h2 = H::new(
        &d,
        &doc(
            r##"{ "type": "script", "id": "s", "x": 20, "y": 20, "width": 200, "height": 120,
              "scriptUri": "./bars.js", "inputs": { "rows": 4, "color": "#ff0000" } }"##,
        ),
    );
    let w = |h: &mut H| {
        let k = h.scene.generated(h.key("s"))[2];
        h.pipe.layout.get(k).unwrap().w
    };
    assert_eq!(w(&mut h), w(&mut h2));

    // Resize: runs again with the new size.
    h.set("s", serde_json::json!({ "width": 100 }));
    assert_eq!(h.runs(), 2);
    let label = *h.scene.generated(s).last().unwrap();
    assert_eq!(
        h.scene.get(label).unwrap().text().unwrap().content.as_ref(),
        "w=100"
    );
    // Back to the previous size: re-attached from the cache.
    h.set("s", serde_json::json!({ "width": 200 }));
    assert_eq!(h.runs(), 2);
    // Inputs: number clamped to max 20.
    h.set("s", serde_json::json!({ "inputs": { "rows": 50 } }));
    assert_eq!(h.scene.generated(s).len(), 21);
    // Moving the page or editing an unrelated node does not run the script.
    let runs = h.runs();
    h.set("page", serde_json::json!({ "x": 300 }));
    h.set("page", serde_json::json!({ "fill": "#eeeeee" }));
    assert_eq!(h.runs(), runs);
    assert!(!h.scene.generated(s).is_empty());
}

#[test]
fn generated_refs_use_document_components() {
    let d = dir("refs");
    std::fs::write(
        d.join("grid.js"),
        "/** @schema 2.22\n * @input cell: ref = \"dot\"\n */\n\
         const out = [];\n\
         for (let i = 0; i < 3; i++) out.push({ type: 'ref', ref: pencil.input.cell, x: i * 30, y: 0,\n\
           descendants: { inner: { fill: i == 1 ? '#00ff00' : '#0000ff' } } });\n\
         return out;\n",
    )
    .unwrap();
    let json = r##"{ "version": "2.22", "children": [
      { "type": "frame", "id": "dot", "reusable": true, "x": 0, "y": 300, "width": 20, "height": 20,
        "fill": "#ff0000", "children": [
          { "type": "rectangle", "id": "inner", "x": 5, "y": 5, "width": 10, "height": 10, "fill": "#000000" } ] },
      { "type": "script", "id": "s", "x": 0, "y": 0, "width": 100, "height": 30, "scriptUri": "grid.js" }
    ] }"##;
    let mut h = H::new(&d, json);
    let s = h.key("s");
    let gens = h.scene.generated(s).to_vec();
    assert_eq!(gens.len(), 3);
    let inst = h.scene.get(gens[1]).unwrap();
    assert_eq!(inst.kind, Kind::Frame);
    let inner = h.scene.children(gens[1])[0];
    assert_eq!(h.scene.generated_owner(inner), Some(s));
    assert!(h.scene.id_path(inner).is_none());
    match &h.scene.get(inner).unwrap().fills[0].paint {
        pen_doc::PaintSpec::Solid(c) => assert_eq!(*c, Color::rgba(0.0, 1.0, 0.0, 1.0)),
        p => panic!("{p:?}"),
    }
    // Editing the component re-resolves the instances (root rebuilt, output re-attached
    // from the cache without running the script).
    let runs = h.runs();
    h.set("dot", serde_json::json!({ "fill": "#123456" }));
    let gens = h.scene.generated(h.key("s")).to_vec();
    assert_eq!(gens.len(), 3);
    assert_eq!(h.runs(), runs);
    match &h.scene.get(gens[0]).unwrap().fills[0].paint {
        pen_doc::PaintSpec::Solid(c) => assert!((c.r - 0x12 as f32 / 255.0).abs() < 1e-3),
        p => panic!("{p:?}"),
    }
}

#[test]
fn errors_render_a_placeholder() {
    let d = dir("errors");
    let cases: &[(&str, &str, &str)] = &[
        (
            "syntax.js",
            "/** @schema 2.11 */\nreturn [ {;\n",
            "Script compile error",
        ),
        ("noschema.js", "return [];\n", "Missing @schema version tag"),
        (
            "throw.js",
            "/** @schema 2.11 */\nconst a = 1;\nnull.x;\nreturn [];\n",
            "Script runtime error",
        ),
        (
            "loop.js",
            "/** @schema 2.11 */\nwhile (true) {}\n",
            "Script runtime error",
        ),
        (
            "many.js",
            "/** @schema 2.11 */\nreturn Array.from({length: 1001}, () => ({type: 'rectangle'}));\n",
            "Too many nodes",
        ),
        (
            "noarray.js",
            "/** @schema 2.11 */\nreturn { type: 'rectangle' };\n",
            "Invalid script output",
        ),
        (
            "noreturn.js",
            "/** @schema 2.11 */\nconst x = 1;\n",
            "Script runtime error",
        ),
        (
            "memory.js",
            "/** @schema 2.11 */\nconst a = []; while (true) a.push(new Array(10000).fill(1));\n",
            "Script runtime error",
        ),
        (
            "reusable.js",
            "/** @schema 2.11 */\nreturn [{ type: 'frame', reusable: true }];\n",
            "Invalid script output",
        ),
        (
            "badinput.js",
            "/** @schema 2.11\n * @input x: vec3 */\nreturn [];\n",
            "Invalid @input type",
        ),
        ("missing.js", "", "Script not found"),
    ];
    let mut nodes = Vec::new();
    for (i, (file, src, _)) in cases.iter().enumerate() {
        if !src.is_empty() {
            std::fs::write(d.join(file), src).unwrap();
        }
        nodes.push(format!(
            r#"{{ "type": "script", "id": "s{i}", "x": {}, "y": 0, "width": 200, "height": 100, "scriptUri": "{file}" }}"#,
            i * 210
        ));
    }
    let json = format!(
        r#"{{ "version": "2.22", "children": [ {} ] }}"#,
        nodes.join(",")
    );
    let t0 = Instant::now();
    let h = H::new(&d, &json);
    let took = t0.elapsed();
    for (i, (file, _, title)) in cases.iter().enumerate() {
        let k = h.key(&format!("s{i}"));
        let err = h
            .scene
            .script_error(k)
            .unwrap_or_else(|| panic!("{file}: no error"));
        assert!(err.starts_with(title), "{file}: {err}");
        assert!(h.scene.generated(k).is_empty());
        // Placeholder + message text.
        let chunk = h.pipe.list.chunks.iter().find(|c| c.root == k).unwrap();
        assert!(
            chunk
                .items
                .iter()
                .any(|it| matches!(it, DisplayItem::Text { node, .. } if *node == k)),
            "{file}: no message drawn"
        );
    }
    let err = h.scene.script_error(h.key("s2")).unwrap();
    assert!(err.contains("> 3: null.x;"), "{err}");
    let err = h.scene.script_error(h.key("s3")).unwrap();
    assert!(err.contains("longer than 2 s"), "{err}");
    // The infinite loop is stopped by the 2 s deadline (plus the other cases).
    assert!(took.as_secs_f32() < 6.0, "{took:?}");
}

#[test]
fn golden_render() {
    let d = dir("golden");
    std::fs::write(
        d.join("rings.js"),
        r##"/**
 * @schema 2.11
 * @input count: number(min=1, max=12) = 5
 * @input color: color = #7c3aed
 */
const out = [];
const cx = pencil.width / 2, cy = pencil.height / 2;
for (let i = 0; i < pencil.input.count; i++) {
  const r = (Math.min(cx, cy) - 4) * (1 - i / pencil.input.count);
  out.push({ type: "ellipse", x: cx - r, y: cy - r, width: 2 * r, height: 2 * r,
    fill: i % 2 ? "#ffffff" : pencil.input.color });
}
out.push({ type: "frame", x: 4, y: 4, width: 60, height: 24, layout: "horizontal", gap: 4,
  padding: 4, fill: "#111827", cornerRadius: 6, children: [
    { type: "rectangle", width: 16, height: 16, fill: "#f59e0b" },
    { type: "rectangle", width: "fill_container", height: 16, fill: "#10b981" } ] });
out.push({ type: "path", x: 0, y: pencil.height - 20, width: pencil.width, height: 20,
  geometry: "M0 20 L" + pencil.width / 2 + " 0 L" + pencil.width + " 20 Z", fill: "#ef4444" });
return out;
"##,
    )
    .unwrap();
    let h = H::new(
        &d,
        &doc(
            r##"{ "type": "script", "id": "s", "x": 20, "y": 10, "width": 200, "height": 140,
              "clip": true, "scriptUri": "rings.js", "inputs": { "count": 6 } }"##,
        ),
    );
    let png = pen_raster::render(
        &h.pipe.list,
        Rect::new(0.0, 0.0, 240.0, 160.0),
        1.0,
        Color::WHITE,
    );
    compare_golden("script_rings", &png);
}

/// Golden comparison (same rules as pen-raster's: bootstrap when missing,
/// `PEN_RASTER_UPDATE_GOLDEN=1` rewrites, mismatches write `*.actual.png`).
fn compare_golden(name: &str, actual: &pen_raster::Pixmap) {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("golden");
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join(format!("{name}.png"));
    let actual_path = dir.join(format!("{name}.actual.png"));
    let update = std::env::var("PEN_RASTER_UPDATE_GOLDEN").is_ok_and(|v| v == "1");
    if update || !path.exists() {
        actual.save_png(&path).unwrap();
        let _ = std::fs::remove_file(&actual_path);
        eprintln!("NOTICE: golden written: {}", path.display());
        return;
    }
    let expected = pen_raster::Pixmap::load_png(&path).unwrap();
    let actual_rt = pen_raster::Pixmap::decode_png(&actual.encode_png().unwrap()).unwrap();
    assert_eq!(
        (expected.width(), expected.height()),
        (actual.width(), actual.height())
    );
    let bad = actual_rt
        .data()
        .chunks(4)
        .zip(expected.data().chunks(4))
        .filter(|(a, e)| {
            a.iter()
                .zip(*e)
                .any(|(x, y)| (*x as i32 - *y as i32).abs() > 8)
        })
        .count();
    if bad as f64 > (expected.width() * expected.height()) as f64 * 0.002 {
        actual.save_png(&actual_path).unwrap();
        panic!(
            "{name}: {bad} pixels differ (wrote {})",
            actual_path.display()
        );
    }
    let _ = std::fs::remove_file(&actual_path);
}

/// The legacy sample scripts (when the extracted app is present) run with their
/// defaults and produce nodes.
#[test]
fn legacy_goodies_run() {
    let src = workspace().join("legacy/extracted/editor/goodies/scripts");
    let Ok(entries) = std::fs::read_dir(&src) else {
        eprintln!("skip: {} not found", src.display());
        return;
    };
    let d = dir("goodies");
    let mut nodes = Vec::new();
    let mut names = Vec::new();
    for (i, e) in entries.flatten().enumerate() {
        let p = e.path();
        if p.extension().is_none_or(|x| x != "js") {
            continue;
        }
        let name = p.file_name().unwrap().to_string_lossy().to_string();
        std::fs::copy(&p, d.join(&name)).unwrap();
        nodes.push(format!(
            r#"{{ "type": "script", "id": "g{i}", "x": {}, "y": {}, "width": 320, "height": 240, "clip": true, "scriptUri": "{name}" }}"#,
            (i % 4) * 340,
            (i / 4) * 260
        ));
        names.push((format!("g{i}"), name));
    }
    let json = format!(
        r#"{{ "version": "2.22", "children": [ {} ] }}"#,
        nodes.join(",")
    );
    let h = H::new(&d, &json);
    for (id, name) in &names {
        let k = h.key(id);
        assert!(
            h.scene.script_error(k).is_none(),
            "{name}: {}",
            h.scene.script_error(k).unwrap_or_default()
        );
        assert!(!h.scene.generated(k).is_empty(), "{name}: no output");
    }
    let png = pen_raster::render(
        &h.pipe.list,
        Rect::new(0.0, 0.0, 1360.0, 780.0),
        1.0,
        Color::WHITE,
    );
    png.save_png(d.join("goodies.png")).unwrap();
}
